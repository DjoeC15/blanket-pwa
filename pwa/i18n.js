let currentLang = 'en';

/** 'system' → première langue du téléphone qu'on sait afficher, sinon anglais. */
function resolveLanguage(pref) {
  if (pref && pref !== 'system' && I18N[pref]) return pref;
  const wanted = navigator.languages?.length ? navigator.languages : [navigator.language || 'en'];
  for (const tag of wanted) {
    const base = String(tag).toLowerCase().split('-')[0];
    if (I18N[base]) return base;
  }
  return 'en';
}

function setLanguage(pref) {
  currentLang = resolveLanguage(pref);
  document.documentElement.lang = currentLang;
  return currentLang;
}

function t(key, vars = {}) {
  let s = I18N[currentLang]?.[key] ?? I18N.en[key] ?? key;
  if (typeof s === 'object') {
    const rule = new Intl.PluralRules(currentLang).select(vars.n ?? 0);
    s = s[rule] ?? s.other;
  }
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
}

/** « aujourd'hui », « il y a 3 jours »… dans la langue courante. */
function relativeDay(ts) {
  if (!ts) return t('neverUsed');
  const start = new Date(); start.setHours(0, 0, 0, 0);
  const days = ts >= start.getTime() ? 0 : Math.ceil((start.getTime() - ts) / 86400000);
  const rtf = new Intl.RelativeTimeFormat(currentLang, { numeric: 'auto' });
  if (days < 7)  return rtf.format(-days, 'day');
  if (days < 35) return rtf.format(-Math.floor(days / 7), 'week');
  return rtf.format(-Math.floor(days / 30), 'month');
}
